#!/usr/bin/env python3
"""Generate the PR skills and review agents for each agent harness.

One shared body per skill or agent holds the text every harness reads; a small
fragment file per harness holds the text only that harness needs.

Sources, under ci/skills/:
  <skill>.md                     shared body of a skill
  agents/<role>.md               shared body of an agent definition
  all/<skill>.md                 slot values every harness shares for one skill,
  all/agents/<role>.md           or for one agent, such as its description
  <harness>/<skill>.md           the harness's slot values for one skill
  <harness>/agents/<role>.md     the harness's slot values for one agent
  <harness>/_common.md           slot values all sources of the harness share

A skill or agent renders for a harness only when the harness has a fragment
file for it. The outputs:
  claude  .claude/skills/<skill>/SKILL.md   .claude/agents/<role>.md
  codex   .codex/skills/<skill>/SKILL.md    .codex/agents/<role>.toml
  pi      .pi/skills/<skill>/SKILL.md       .pi/agents/<role>.md

A Codex agent is a native agent role, which spawn_agent takes as agent_type.
Its frontmatter value holds the role's TOML keys (name, description, and
model_reasoning_effort when the role always runs at one effort), and the
rendered body becomes its developer_instructions. A role's
model_reasoning_effort overrides the reasoning_effort spawn_agent passes, so a
role that runs at several efforts leaves it out.

Slots. In a shared body, a line holding only {{name}} is a block slot: the
renderer replaces the whole line, newline included, with the value, so an
empty value removes the line. {{name}} anywhere else in a line is an inline
slot, whose value must be a single line. A value may itself contain inline
slots, such as a harness's frontmatter naming {{description}} from all/.

Fragment files. A line "=== name" starts the value of a slot. The value runs to
the next "=== " line or the end of the file, every character included: a blank
line before the next "===" belongs to the value. An inline value drops its
final newline. A skill's own fragment file overrides _common.md. A value set
in all/ applies to every harness, and no harness may set it again.

The renderer fails on a slot a source uses that the harness doesn't define, on
a fragment value no source uses, on a multi-line inline value, and on a value
both all/ and a harness set, so no harness text goes missing, stays behind
unused, or drifts from the other harnesses.

Usage:
  python3 ci/skills/render.py           write the generated files
  python3 ci/skills/render.py --check   exit 1 when a generated file is stale
"""
import argparse
import re
import sys
from pathlib import Path

try:
    import tomllib
except ModuleNotFoundError:
    sys.exit('ERROR: ci/skills/render.py needs Python 3.11 or newer, for tomllib')

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'ci' / 'skills'
SHARED_DIR = SRC / 'all'
HARNESSES = {'claude': '.claude', 'codex': '.codex', 'pi': '.pi'}
AGENT_DIRS = {'claude': '.claude/agents', 'codex': '.codex/agents', 'pi': '.pi/agents'}
TOML_AGENTS = {'codex'}
SLOT = re.compile(r'\{\{([a-z0-9_-]+)\}\}')
HEADER_MARK = 'Generated by ci/skills/render.py'
HEADER_TAIL = ' from ci/skills/{src}: edit the source, then run the script.'
MD_HEADER = '<!-- ' + HEADER_MARK + HEADER_TAIL + ' -->\n'
TOML_HEADER = '# ' + HEADER_MARK + HEADER_TAIL + '\n'


class RenderError(Exception):
    pass


def rel(path):
    return path.relative_to(ROOT).as_posix()


def parse_fragments(path):
    values = {}
    name = None
    buf = []
    for line in path.read_text().splitlines(keepends=True):
        if line.startswith('=== '):
            if name is not None:
                values[name] = ''.join(buf)
            name = line[4:].strip()
            if not SLOT.fullmatch('{{' + name + '}}'):
                raise RenderError(f'{rel(path)}: bad slot name {name!r}')
            if name in values:
                raise RenderError(f'{rel(path)}: slot {name} defined twice')
            buf = []
        elif name is None:
            raise RenderError(f'{rel(path)}: text before the first "=== <slot>" line')
        else:
            buf.append(line)
    if name is not None:
        values[name] = ''.join(buf)
    return values


def render(text, values, where):
    out = []
    used = set()

    def value(name, stack):
        if name not in values:
            raise RenderError(f'{where}: no value for {{{{{name}}}}}')
        if name in stack:
            raise RenderError(f'{where}: {{{{{name}}}}} refers to itself through {" -> ".join(stack)}')
        used.add(name)
        return SLOT.sub(lambda m: inline(m.group(1), stack + (name,)), values[name])

    def inline(name, stack=()):
        v = value(name, stack)
        v = v[:-1] if v.endswith('\n') else v
        if '\n' in v:
            raise RenderError(f'{where}: {{{{{name}}}}} is inline but its value has several lines')
        return v

    for line in text.splitlines(keepends=True):
        m = SLOT.fullmatch(line.rstrip('\n'))
        if m:
            v = value(m.group(1), ())
            out.append(v if v == '' or v.endswith('\n') else v + '\n')
        else:
            out.append(SLOT.sub(lambda m: inline(m.group(1)), line))
    return ''.join(out), used


def add_header(text, src, where):
    if not text.startswith('---\n'):
        raise RenderError(f'{where}: output does not start with frontmatter')
    end = text.index('\n---\n', 3) + 5
    return text[:end] + MD_HEADER.format(src=src) + text[end:]


def render_toml_agent(text, values, src, target):
    """Render a native Codex role: TOML keys, then the body as developer_instructions."""
    where = rel(target)
    keys, used = render('{{frontmatter}}\n', values, where)
    body, body_used = render(text, {**values, 'frontmatter': ''}, where)
    body = body.lstrip('\n')
    if "'''" in body:
        raise RenderError(f"{where}: the body contains ''', which ends a TOML literal string")
    out = (TOML_HEADER.format(src=src) + keys
           + "developer_instructions = '''\n" + body + "'''\n")
    try:
        parsed = tomllib.loads(out)
    except tomllib.TOMLDecodeError as e:
        raise RenderError(f'{where}: invalid TOML: {e}')
    if parsed.get('name') != target.stem or not parsed.get('description'):
        raise RenderError(f'{where}: needs name = "{target.stem}" and a description')
    if 'description' in values:
        description, _ = render('{{description}}\n', values, where)
        if parsed['description'] != description.rstrip('\n'):
            raise RenderError(f'{where}: the TOML description differs from {{{{description}}}}; '
                              'it may hold a quote or a backslash')
    if parsed['developer_instructions'] != body:
        raise RenderError(f'{where}: developer_instructions does not round-trip')
    return out, used | body_used


def fragment_files(frag_dir, sources, kind, skip=None):
    """The fragment files of a directory, each checked to have a shared source."""
    for frag in sorted(frag_dir.glob('*.md')):
        if frag != skip and frag.stem not in sources:
            raise RenderError(f'{rel(frag)}: no shared {kind} {frag.stem} in ci/skills')


def outputs():
    """Map each generated path to its content."""
    result = {}
    kinds = {
        'skill': ({p.stem: p for p in sorted(SRC.glob('*.md'))}, ''),
        'agent': ({p.stem: p for p in sorted((SRC / 'agents').glob('*.md'))}, 'agents'),
    }
    shared = {}
    for kind, (sources, sub) in kinds.items():
        fragment_files(SHARED_DIR / sub, sources, kind)
        for name in sources:
            path = SHARED_DIR / sub / f'{name}.md'
            shared[kind, name] = (path, parse_fragments(path) if path.exists() else {}, set())

    for harness, out_dir in HARNESSES.items():
        hdir = SRC / harness
        common_path = hdir / '_common.md'
        common = parse_fragments(common_path) if common_path.exists() else {}
        common_used = set()
        for kind, (sources, sub) in kinds.items():
            fragment_files(hdir / sub, sources, kind, skip=common_path)
            for name, src in sources.items():
                frag = hdir / sub / f'{name}.md'
                if not frag.exists():
                    continue
                own = parse_fragments(frag)
                shared_path, shared_values, shared_used = shared[kind, name]
                again = sorted(set(shared_values) & (set(common) | set(own)))
                if again:
                    raise RenderError(f'{rel(frag)}: {", ".join(again)} already set for every harness '
                                      f'in {rel(shared_path)}')
                values = {**shared_values, **common, **own}
                src_name = src.relative_to(SRC).as_posix()
                if kind == 'agent' and harness in TOML_AGENTS:
                    target = ROOT / AGENT_DIRS[harness] / f'{name}.toml'
                    text, used = render_toml_agent(src.read_text(), values, src_name, target)
                else:
                    if kind == 'skill':
                        target = ROOT / out_dir / 'skills' / name / 'SKILL.md'
                    else:
                        target = ROOT / AGENT_DIRS[harness] / f'{name}.md'
                    text, used = render(src.read_text(), values, rel(target))
                    text = add_header(text, src_name, rel(target))
                unused = sorted(set(own) - used)
                if unused:
                    raise RenderError(f'{rel(frag)}: no source uses {", ".join(unused)}')
                common_used |= used & set(common) - set(own)
                shared_used |= used & set(shared_values)
                result[target] = text
        unused = sorted(set(common) - common_used)
        if unused:
            raise RenderError(f'{rel(common_path)}: no source uses {", ".join(unused)}')
    for path, shared_values, shared_used in shared.values():
        unused = sorted(set(shared_values) - shared_used)
        if unused:
            raise RenderError(f'{rel(path)}: no harness uses {", ".join(unused)}')
    return result


def stale_outputs(result):
    """Generated files on disk that no source produces any more."""
    found = []
    for harness, out_dir in HARNESSES.items():
        skill_files = (ROOT / out_dir).glob('skills/*/SKILL.md')
        agent_dir = ROOT / AGENT_DIRS[harness]
        for path in [*skill_files, *agent_dir.glob('*.md'), *agent_dir.glob('*.toml')]:
            if path not in result and HEADER_MARK in path.read_text():
                found.append(path)
    return found


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--check', action='store_true', help='report stale generated files and change nothing')
    args = ap.parse_args()
    try:
        result = outputs()
    except RenderError as e:
        print(f'ERROR: {e}', file=sys.stderr)
        return 2
    stale = stale_outputs(result)
    changed = [p for p, text in result.items() if not p.exists() or p.read_text() != text]
    if args.check:
        for p in changed:
            print(f'out of date: {rel(p)}')
        for p in stale:
            print(f'no source: {rel(p)}')
        if changed or stale:
            print('Edit the sources in ci/skills/ and run: python3 ci/skills/render.py', file=sys.stderr)
            return 1
        print(f'{len(result)} generated files are up to date')
        return 0
    for p in changed:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(result[p])
        print(f'wrote {rel(p)}')
    for p in stale:
        p.unlink()
        if p.name == 'SKILL.md' and not any(p.parent.iterdir()):
            p.parent.rmdir()
        print(f'removed {rel(p)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
